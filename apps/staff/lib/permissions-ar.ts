const BY_CODE = new Map(ENTRIES.map(([code, title, detail]) => [code, { title, detail }]));

/**
 * تعريب صلاحية واحدة.
 *
 * إن وصل كود غير معروف (إضافة مستقبلية) لا نُظهره خاماً: نشتق عنواناً من
 * الوحدة + الفعل بالعربية، ونضع الكود في `title` (تلميح تقني) لا في النص.
 */
export function describePermissionAr(code: string, moduleKey?: string): PermissionDescription {
  const module = moduleKey ?? code.split('.')[0] ?? 'tenant';
  const moduleAr = PERMISSION_MODULE_AR[module] ?? 'صلاحيات أخرى';
  const known = BY_CODE.get(code);
  if (known) return { ...known, moduleAr };

  const parts = code.split('.');
  const action = parts[parts.length - 1] ?? '';
  const actionAr = UNKNOWN_ACTION_AR[action] ?? 'الوصول';
  return {
    title: `${actionAr} — ${moduleAr}`,
    detail: 'صلاحية تشغيلية داخل هذه الوحدة.',
    moduleAr,
  };
}

