export function permissionLabelAr(code: string): string {
  const parts = code.split('.');
  const action = parts.pop() ?? '';
  const resource = RESOURCES[parts.join('.')];
  // An unrecognised code must not be presented as a meaningful grant. Keep its identifier
  // searchable in the role editor, while signalling that its description needs review.
  if (!resource || !ACTIONS[action]) return 'صلاحية غير مصنّفة — راجع مسؤول النظام';
  return `${ACTIONS[action]} ${resource}`;
}

export function systemRoleNameAr(name: string): string {
  const names: Record<string, string> = {
    Owner: 'مالك المنشأة',
    Accountant: 'محاسب',
    Cashier: 'أمين الصندوق',
  };
  return names[name] ?? name;
}
