-- 🚐 عددُ المركبة كلها — من «عددٍ لكلّ أمر» إلى «عددٍ للسيارة» يُشتقّ منه نصيب الأمر.
--
-- القرار (من مالك المنتج، 2026-10-15): `actualRemainingQty` **عددُ المركبة كلها** كما تُعدّ
-- فعلاً، وعلى الخادم أن يطرح منه العهدةَ الأخرى الجالسة في السيارة نفسها قبل حساب الفرق، فلا
-- يُشطب شيءٌ بلا مسؤولية.
--
-- وما كان قبله (مقاسٌ لا مقدَّر — منشأة العرض، ‏2026-10-15):
--   • مستند الجرد الرسمي **مطلق**: `createAdjustment` يُقارن العدد المُعلن برصيد السيارة كله
--     للصنف (`stock_balances.quantity`) لحظة الترحيل، فيضبط الرصيد على العدد المُعلن.
--   • والعدد المُعلن كان **نصيب هذا الأمر وحده**. فإقفالُ أمرٍ واحد يشطب عهدةَ الأوامر الأخرى
--     الجالسة في السيارة نفسها: `VLO-0004` امتصّ مستندُه 18.00 كجم هي عهدةُ `VLO-0001`
--     **المفتوحة**، و`VLO-0005` امتصّ بعدها 8.00 كجم هي عهدةُ `VLO-0004`. وصار رصيد السيارة
--     4.50 كجم لعهدةٍ مفتوحةٍ مقدارها 18.00 ⇒ نقصُ 13.50 كجم لا يقع في ذمّة أحد.
--   • والحالة مُعادةُ الإنتاج في اختبار: سيارةٌ واحدة فيها عهدتان (‏20 + 10)، بيع 4 من الثانية،
--     وعددٌ صادقٌ لها وحدها (‏5.5) ⇒ الرصيد 5.50 والعهدةُ المفتوحة الأخرى تنقص 14.50
--     (‏`apps/api/test/van-sales-stock-settlement.spec.ts`، حالة `cov`).
--
-- التنفيذ لا يحتاج جدولاً جديداً ولا طرفاً محاسبياً جديداً: عمودان على أمر التحميل نفسه.
--
--   • `vehicle_count_qty` = العدد المُعلن **للمركبة كلها** (‏V).
--   • `other_custody_qty`  = ما طرحه الخادم منه لحظة الإقفال (‏O = max(0, B − E)) حيث
--     B رصيد السيارة الرسمي للصنف وE متوقّعُ البقاء لهذا الأمر — وهي المتطابقة التي صَحّت
--     عند الإقفالين الممتصّين أعلاه (‏28 − 10 = 18، و14 − 6 = 8) فهي تعريفٌ لا تقدير.
--
-- ومنها يشتقّ الخادم `actual_remaining_qty = max(0, V − O)` (نصيبُ هذا الأمر من العدد الفعلي)،
-- ويُرسل مستند الجرد بـ`counted_qty = V` لا بنصيب الأمر. فيصير فرقُ المستند (‏V − B) مساوياً
-- بالضبط لفرق اعتماد الأمر (‏E − A) ⇒ **الامتصاص صفر**: ما يُشطب من المخزون هو ما يُحاسب عليه
-- صاحبه، لا حركةٌ إضافية لا يملكها أحد. (والجبر: إذا B ≥ E فإنّ A = V − B + E فيكون
-- E − A = B − V، وهو فرقُ المستند بمقداره.)
--
-- وإذا كان V < O فالنقصُ الزائد يخصّ عهدةً أخرى: **يُرفض** الإقفال (‏422) ولا يُحمَّل على هذا
-- الأمر ولا يُشطب بصمت — فإمّا تصحيحُ العدد وإمّا إقفالُ أمرِ العهدة الأخرى أوّلاً.
--
-- والعمودان **دليلٌ لا وصف**: يُخزَّنان كما قِيلا لحظة الإقفال، فلا يُعاد حسابهما للعرض فيتغيّر
-- المعروض بعد تغيّر الأرصدة — وهو المبدأ نفسه الذي كُتب به `shortage_charge_amount` (‏0128).
--
-- ولا backfill عن قصد: ‏NULL يعني «إقفالٌ بعددٍ لكلّ أمر» وهو السلوك السابق حرفياً، فتبقى
-- الأوامر التاريخية كما أُقفلت ولا يُختلَع لها عددُ مركبةٍ لم يقله أحد.

ALTER TABLE van_load_orders
  ADD COLUMN IF NOT EXISTS vehicle_count_qty numeric(18,4),
  ADD COLUMN IF NOT EXISTS other_custody_qty numeric(18,4);

COMMENT ON COLUMN van_load_orders.vehicle_count_qty IS
  '🚐 عددُ المركبة كلها كما أُعلن عند الإقفال — NULL يعني أنّ الإقفال تمّ بعددٍ لكلّ أمر (السلوك السابق).';
COMMENT ON COLUMN van_load_orders.other_custody_qty IS
  '🚐 ما طرحه الخادم من عدد المركبة لأنه عهدةُ أوامرَ أخرى في السيارة نفسها (‏max(0, رصيد السيارة − متوقّع البقاء لهذا الأمر)) — دليلٌ كما حُسب لحظة الإقفال.';
